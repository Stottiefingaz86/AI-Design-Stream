#!/usr/bin/env node
/**
 * Push the compiled Lumen tokens into the pretend live site (apps/live-site, Next 14 + Tailwind 3).
 *
 * Writes apps/live-site/app/lumen.css:
 *   :root { …primitives… }            from tokens/dist/base.css (the @theme block is Tailwind-4-only and is dropped)
 *   [data-brand='x'] / .dark blocks    from tokens/dist/brands/*.css
 *
 * Run after `npm run tokens:sync`. Never hand-edit the output.
 */
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'tokens', 'dist');
const OUT = path.join(ROOT, 'apps', 'live-site', 'app', 'lumen.css');

const base = await readFile(path.join(DIST, 'base.css'), 'utf8').catch(() => null);
if (!base) {
  console.error('tokens/dist/base.css missing — run `npm run tokens:sync` first.');
  process.exit(1);
}
const rootBlock = base.slice(base.indexOf(':root {'), base.indexOf('@theme inline')).trim();
const brandFiles = (await readdir(path.join(DIST, 'brands'))).filter((f) => f.endsWith('.css')).sort();
const brands = await Promise.all(brandFiles.map((f) => readFile(path.join(DIST, 'brands', f), 'utf8')));

const css =
  `/* GENERATED by scripts/sync-live-site-theme.mjs from tokens/dist — do not edit. */\n` +
  `/* Lumen tokens for the live site. Brand is selected with <html data-brand="…">, dark mode with .dark. */\n\n` +
  rootBlock +
  '\n\n' +
  brands.map((b) => b.replace(/^\/\*.*\*\/\n/, '').trim()).join('\n\n') +
  '\n';

await mkdir(path.dirname(OUT), { recursive: true });
await writeFile(OUT, css);
console.log(`live-site theme: ${brandFiles.map((f) => f.replace('.css', '')).join(', ')} → ${path.relative(ROOT, OUT)}`);
