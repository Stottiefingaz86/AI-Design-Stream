function previewSlug(diskPath) {
  return diskPath.replace(/\//g, '__')
}

async function main() {
  const byKey = {}
  const pack = []
  const previewDir = path.join(liveSite, 'public/ba/preview')
  const previewManifest = {}

  await fs.rm(previewDir, { recursive: true, force: true }).catch(() => {})
  await fs.mkdir(previewDir, { recursive: true })

  for (const file of FILES) {
    const abs = path.join(liveSite, file.diskPath)
    let text = ''
    try {
      text = await fs.readFile(abs, 'utf8')
    } catch {
      console.warn(`[bundle-ba-artifacts] missing ${file.diskPath}`)
      continue
    }
    for (const key of file.keys) {
      byKey[key] = { path: file.diskPath, text }
    }
    pack.push({ zipPath: file.zipPath, path: file.diskPath, text })

    const slug = previewSlug(file.diskPath)
    await fs.writeFile(path.join(previewDir, `${slug}.txt`), text, 'utf8')
    previewManifest[file.diskPath] = slug
    for (const key of file.keys) {
      previewManifest[key] = slug
    }
  }

  await fs.writeFile(
    path.join(previewDir, 'manifest.json'),
    JSON.stringify(previewManifest, null, 2),
    'utf8',
  )

  await fs.mkdir(path.dirname(outFile), { recursive: true })
  const body = `/* AUTO-GENERATED by scripts/bundle-ba-artifacts.mjs — do not edit */
export type BaArtifactEntry = { path: string; text: string }

export const BA_ARTIFACT_BY_KEY: Record<string, BaArtifactEntry> = ${JSON.stringify(byKey, null, 2)}

export const BA_HANDOVER_PACK: { zipPath: string; path: string; text: string }[] = ${JSON.stringify(pack, null, 2)}
`
  await fs.writeFile(outFile, body, 'utf8')
  console.log(
    `[bundle-ba-artifacts] ${Object.keys(byKey).length} keys, ${pack.length} pack files → lib/ba/artifact-bundle.generated.ts + public/ba/preview/`,
  )
}

main().catch((err) => {
  console.error('[bundle-ba-artifacts]', err)
  process.exit(1)
})
